const simplify = (value: string) => value.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g,"");
export function resolveWorldArt(city?: string | null, country?: string | null) {
  const cityTerms = (city || "").split(",").map(simplify).filter(Boolean);
  for (const term of cityTerms) {
    const key = CITY_ALIASES[term] || term;
    if (CITY_ART[key]) return CITY_ART[key];
  }
  for (const term of [...cityTerms, simplify(country || "")]) {
    const countryKey = ISO_COUNTRY[term.toUpperCase()] || COUNTRY_ALIASES[term] || term;
    const cityKey = COUNTRY_CITY[countryKey];
    if (cityKey) return CITY_ART[cityKey];
  }
  return null;
}
