-- Invariant: only the trusted server may change incident state. Never accept
-- tenant/scope/severity selection from a Telegram button.
CREATE OR REPLACE FUNCTION public.tok_sentinel_decide(
  p_incident_id uuid, p_token_hash text, p_chat_id text,
  p_message_id bigint, p_actor text, p_decision text
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
SET search_path = '' AS $$
DECLARE v_incident public.tok_sentinel_incidents%ROWTYPE;
BEGIN
  IF auth.role() <> 'service_role' THEN
    RAISE EXCEPTION 'sentinel_service_role_required' USING ERRCODE = '42501';
  END IF;
  IF p_decision NOT IN ('approve', 'reject') OR length(p_actor) NOT BETWEEN 3 AND 160 THEN
    RAISE EXCEPTION 'sentinel_invalid_decision' USING ERRCODE = '22023';
  END IF;
  SELECT * INTO v_incident FROM public.tok_sentinel_incidents
    WHERE id = p_incident_id FOR UPDATE;
  IF NOT FOUND OR v_incident.status <> 'awaiting_approval'
    OR v_incident.approval_token_hash IS NULL
    OR v_incident.approval_token_hash IS DISTINCT FROM p_token_hash
    OR v_incident.approval_expires_at <= now()
    OR v_incident.approval_expires_at IS NULL
    OR v_incident.decision_chat_id IS DISTINCT FROM p_chat_id
    OR v_incident.decision_message_id IS DISTINCT FROM p_message_id THEN
    RAISE EXCEPTION 'sentinel_stale_or_unverified_decision' USING ERRCODE = '22023';
  END IF;
  IF p_decision = 'approve' THEN
    INSERT INTO public.tok_sentinel_containments(incident_id,scope,target_id,reason)
      VALUES (v_incident.id,v_incident.scope,v_incident.target_id,
        left('Approved containment: ' || v_incident.category,400));
  END IF;
  UPDATE public.tok_sentinel_incidents SET
    status = CASE WHEN p_decision='approve' THEN 'contained' ELSE 'rejected' END,
    approval_token_hash = NULL, approval_expires_at = NULL,
    decision_actor = p_actor, decided_at = now()
    WHERE id = v_incident.id;
  INSERT INTO public.tok_sentinel_events(incident_id,event_type,actor,evidence)
    VALUES(v_incident.id,
      CASE WHEN p_decision='approve' THEN 'containment_approved' ELSE 'containment_rejected' END,
      p_actor,pg_catalog.jsonb_build_object('scope',v_incident.scope,'category',v_incident.category));
  RETURN pg_catalog.jsonb_build_object('incidentId',v_incident.id,
    'status',CASE WHEN p_decision='approve' THEN 'contained' ELSE 'rejected' END,
    'scope',v_incident.scope);
END;
$$;

CREATE OR REPLACE FUNCTION public.tok_sentinel_release(
  p_incident_id uuid, p_actor text
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
SET search_path = '' AS $$
DECLARE v_scope text;
BEGIN
  IF auth.role() <> 'service_role' THEN
    RAISE EXCEPTION 'sentinel_service_role_required' USING ERRCODE = '42501';
  END IF;
  IF length(coalesce(p_actor,'')) NOT BETWEEN 3 AND 160 THEN
    RAISE EXCEPTION 'sentinel_invalid_actor' USING ERRCODE = '22023';
  END IF;
  SELECT scope INTO v_scope FROM public.tok_sentinel_incidents
    WHERE id=p_incident_id AND status='contained' FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'sentinel_not_contained' USING ERRCODE = '22023';
  END IF;
  UPDATE public.tok_sentinel_containments SET
    released_at = now(), released_by=p_actor
    WHERE incident_id=p_incident_id AND released_at IS NULL;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'sentinel_missing_active_containment' USING ERRCODE = '22023';
  END IF;
  UPDATE public.tok_sentinel_incidents SET status='released'
    WHERE id=p_incident_id;
  INSERT INTO public.tok_sentinel_events(incident_id,event_type,actor,evidence)
    VALUES(p_incident_id,'containment_released',p_actor,
      pg_catalog.jsonb_build_object('scope',v_scope));
  RETURN pg_catalog.jsonb_build_object('incidentId',p_incident_id,'status','released');
END;
$$;

-- Checks cannot be circumvented by a direct browser-to-PostgREST mutation.
-- Checks remain read-only and do not modify transaction state.
CREATE OR REPLACE FUNCTION public.tok_sentinel_write_allowed(
  p_operation text, p_restaurant_id uuid DEFAULT NULL, p_user_id uuid DEFAULT NULL
) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = '' AS $$
  SELECT NOT EXISTS (
    SELECT 1 FROM public.tok_sentinel_containments c
    WHERE c.released_at IS NULL
      AND (c.scope='global'
        OR (c.scope=p_operation AND p_operation IN ('payments','administration'))
        OR (c.scope='restaurant' AND p_restaurant_id IS NOT NULL AND c.target_id=p_restaurant_id)
        OR (c.scope='account' AND p_user_id IS NOT NULL AND c.target_id=p_user_id))
  );
$$;
REVOKE ALL ON FUNCTION public.tok_sentinel_decide(uuid,text,text,bigint,text,text) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.tok_sentinel_release(uuid,text) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.tok_sentinel_write_allowed(text,uuid,uuid) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.tok_sentinel_decide(uuid,text,text,bigint,text,text) TO service_role;
GRANT EXECUTE ON FUNCTION public.tok_sentinel_release(uuid,text) TO service_role;
GRANT EXECUTE ON FUNCTION public.tok_sentinel_write_allowed(text,uuid,uuid) TO service_role, anon, authenticated;

