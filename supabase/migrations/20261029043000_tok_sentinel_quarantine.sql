-- TOK Sentinel: opt-in, auditable containment plane.
-- No incident, containment, or production secret is seeded by this migration.
-- Existing Stripe webhooks/service_role reconciliation remain reachable.
CREATE TABLE IF NOT EXISTS public.tok_sentinel_incidents (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  fingerprint text NOT NULL UNIQUE CHECK (fingerprint ~ '^[0-9a-f]{64}$'),
  category text NOT NULL CHECK (category IN (
    'authorization_probing', 'payment_abuse', 'distributed_probing',
    'confirmed_rls_bypass', 'confirmed_privilege_compromise',
    'confirmed_destructive_activity'
  )),
  severity text NOT NULL CHECK (severity IN ('watch', 'high', 'critical')),
  scope text NOT NULL CHECK (scope IN ('account', 'restaurant', 'payments', 'administration', 'global')),
  target_id uuid,
  status text NOT NULL DEFAULT 'awaiting_approval'
    CHECK (status IN ('awaiting_approval', 'contained', 'rejected', 'released')),
  report jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(report) = 'object'),
  evidence_ids uuid[] NOT NULL DEFAULT '{}',
  occurrence_count integer NOT NULL DEFAULT 1 CHECK (occurrence_count >= 1),
  approval_token_hash text CHECK (approval_token_hash ~ '^[a-f0-9]{64}$'),
  approval_expires_at timestamptz,
  decision_chat_id text,
  decision_message_id bigint,
  decision_actor text,
  decided_at timestamptz,
  first_seen_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT tok_sentinel_target_required CHECK (
    scope NOT IN ('account', 'restaurant') OR target_id IS NOT NULL
  ),
  CONSTRAINT tok_sentinel_global_critical_only CHECK (
    scope <> 'global' OR
      (severity = 'critical' AND category IN (
        'confirmed_rls_bypass',
        'confirmed_privilege_compromise',
        'confirmed_destructive_activity'
      ))
  )
);
CREATE INDEX IF NOT EXISTS tok_sentinel_incidents_status_recent
  ON public.tok_sentinel_incidents(status, last_seen_at DESC);

CREATE TABLE IF NOT EXISTS public.tok_sentinel_containments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  incident_id uuid NOT NULL UNIQUE REFERENCES public.tok_sentinel_incidents(id),
  scope text NOT NULL CHECK (scope IN ('account', 'restaurant', 'payments', 'administration', 'global')),
  target_id uuid,
  reason text NOT NULL CHECK (length(reason) BETWEEN 3 AND 400),
  activated_at timestamptz NOT NULL DEFAULT now(),
  released_at timestamptz,
  released_by text,
  CONSTRAINT tok_sentinel_containment_target CHECK (
    scope NOT IN ('account', 'restaurant') OR target_id IS NOT NULL
  )
);
CREATE INDEX IF NOT EXISTS tok_sentinel_containments_active
  ON public.tok_sentinel_containments(scope, target_id) WHERE released_at IS NULL;

CREATE TABLE IF NOT EXISTS public.tok_sentinel_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  incident_id uuid REFERENCES public.tok_sentinel_incidents(id),
  event_type text NOT NULL CHECK (length(event_type) BETWEEN 3 AND 64),
  actor text NOT NULL CHECK (length(actor) BETWEEN 3 AND 160),
  evidence jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(evidence) = 'object'),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS tok_sentinel_events_by_incident
  ON public.tok_sentinel_events(incident_id, created_at DESC);

-- Even service-role requests cannot rewrite or remove forensic history.
-- This is an append-only in-project safeguard, not an off-project WORM archive.
CREATE OR REPLACE FUNCTION public.tok_sentinel_protect_event_history()
RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  RAISE EXCEPTION 'sentinel_events_append_only' USING ERRCODE = '42501';
END;
$$;
REVOKE ALL ON FUNCTION public.tok_sentinel_protect_event_history()
  FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS trg_tok_sentinel_events_append_only ON public.tok_sentinel_events;
CREATE TRIGGER trg_tok_sentinel_events_append_only
  BEFORE UPDATE OR DELETE ON public.tok_sentinel_events
  FOR EACH ROW EXECUTE FUNCTION public.tok_sentinel_protect_event_history();

