DROP POLICY IF EXISTS "Restaurant members can read campaign studio runs"
  ON public.campaign_studio_runs;
CREATE POLICY "Restaurant members can read campaign studio runs"
  ON public.campaign_studio_runs
  FOR SELECT
  TO authenticated
  USING (
    public.auth_is_admin()
    OR public.auth_owns_restaurant(restaurant_id)
  );

